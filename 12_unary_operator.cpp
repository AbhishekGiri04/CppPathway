#include<iostream>
using namespace std;

int main(){
    int a=0;
    int b=0;
    cout<<"Pre-increment operator: "<<++a<<endl;
    cout<<"Post-increment operator: "<<b++<<endl;
    cout<<"Now, value of a: "<<a<<endl;
    cout<<"Now, value of b: "<<b<<endl; 
    cout<<"Pre-decrement operator: "<<--a<<endl;
    cout<<"Post-decrement operator: "<<b--<<endl;
    cout<<"Now, value of a: "<<a<<endl;
    cout<<"Now, value of b: "<<b<<endl; 
    return 0;
}